## 四、什么时候吃

很多人走完全程才发现自己没吃东西——然后突然低血糖，头晕、发软。

**规则：每 45–60 分钟吃一点**，哪怕不饿。

- 出发 1 小时后开始
- 上坡前吃一点（提供能量）
- 感觉累之前吃，不是累之后

## 五、关于咖啡和酒

