## 四、夜爬的特殊风险

### 1. 看不清路

夜间的判断力下降明显，容易踩空、走错岔路。

**应对**：走熟悉的路线；用轨迹导航；头灯亮度要够（200 流明以上）。

### 2. 冷

凌晨是一天最冷的时候，比白天低 8–10 度。而且你会停下来等日出。

**应对**：多带一层保暖，带热水。

### 3. 困

凌晨 3–4 点是人体最困的时段，判断力和反应速度都会下降。

**应对**：出发前睡一会儿（哪怕 2 小时）；带咖啡或茶。

### 4. 遇不到人

夜爬时一旦出问题，很难有人帮忙。

**应对**：至少 3 人；走成熟路线；出发前报备。

