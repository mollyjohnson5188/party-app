**判断标准**：出发时包里应该有"感觉有点重"的水量。如果觉得轻松，说明带少了。

### 怎么喝

- **出发前 1 小时喝 500ml**
- 每 30 分钟喝 100–150ml，**主动喝，不等渴**
- 上坡前后各喝几口
- 别一次猛灌一大瓶（会胃胀）

### 电解质

大量出汗时只喝白水，可能引发低钠（头晕、恶心、肌肉抽搐）。

**夏季长线**：带电解质片或盐丸，每 1–2 小时补一次。

