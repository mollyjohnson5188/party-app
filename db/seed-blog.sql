## 三个容易忽略的细节

### 1. 走完一定要拉伸，而且当天就拉

重点拉**股四头肌、小腿、臀部**。走完当天拉 10 分钟，比第二天疼了再拉有效得多。

### 2. 下坡用登山杖，真的省腿

