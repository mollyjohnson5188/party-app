### 3. 上坡用小步慢走，不要冲

新手最容易犯的错是上坡时想「一口气冲上去」，结果心率飙到 170，必须停下喘 5 分钟。

正确做法：**用能正常说话的节奏走**，步子小一点，宁可慢但不停。整体速度反而更快。

