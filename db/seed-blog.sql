## 保证金制的具体设计

核心逻辑只有一句：**你只要来了，钱一分不少退你；你不来，你的钱给来了的人。**

具体规则：

- **报名时冻结**：通过持牌支付机构的预授权把保证金冻结住，钱不进入平台账户
- **到场核销后全额解冻**：T0 开始后 60 分钟到 120 分钟内扫码签到，保证金原路全额退回
- **爽约扣划**：T0+60 分钟后仍未签到，进入爽约候选；T0+120 分钟自动判定爽约。被扣的保证金**全部**分给实际到场签到的人
- **平台分文不取**：扣划的钱 100% 流向参会者，平台不抽成
- **取消即退**：自己取消、主理人取消、活动被取消，保证金都全额退还

**关键点**：平台从头到尾不碰这笔钱，也不参与结算。资金流走的是持牌机构的冻结/解冻/分账能力，平台只负责判定「该不该解冻」这个状态。

## 为什么这套规则能起作用

因为它把「承诺」变成了有成本的事，但**只惩罚真的失约**。

- 认真要去的人：零成本。到场钱就回来了。
- 随手点「+1」的人：会被扣钱，而且钱不是给平台，是给那些真的来了的人。
- 主理人：不用预先垫钱订车，因为报名人数是有真实承诺的。

这不是「惩罚机制」，是**让口头承诺变得可信**的一种办法。

## 一些我们做得很克制的地方

- **不设「不予退还」的条款**。所有合规场景下保证金都全额退，不存在「平台没收」。
- **不做余额、不做钱包**。钱不进平台，就不可能被挪用，也不需要资金存管。
- **所有资金和信用变动都是幂等的**。同一次扣划不会重复执行，每一次状态变化都有审计记录。
- **爽约不是永久的**。信用分会恢复，也有申诉通道。我们知道有人是真的遇到意外。

## 它解决不了什么

说实话，保证金制解决的是「随意报名」，不是「所有失约」。

有人会遇到突发情况，这是任何机制都消除不了的。我们只是让这类事情的概率降下来，并且让受损的一方（真的到场的人）得到一点补偿。

> 一个健康的组局环境，靠的不是严格的惩罚，而是**大家都相信对方会来**。

