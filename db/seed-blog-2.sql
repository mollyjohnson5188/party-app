这就叫**代收代付**，在支付行业里俗称"二清"（二次清算）。

## 二、为什么这是红线

因为"代收代付"本质上是**在没有支付牌照的情况下做了支付机构的活**。

这带来几个实际风险：

1. **资金池风险**：钱在平台账户里停留，就有被挪用、被冻结、卷款跑路的可能
2. **合规风险**：需要支付牌照，或者必须通过持牌机构做合规的资金存管
3. **用户风险**：平台一旦出问题，用户的押金、余额都可能拿不回来

**这不是"要不要做"的策略问题，是"能不能做"的合规问题。**

## 三、我们实际怎么做

核心设计：**保证金全程通过持牌支付机构的冻结/解冻/分账能力处理，钱从不进入平台账户。**

具体流程：

1. 报名时 → 调用支付机构的**预授权冻结**，钱被冻结在用户的支付账户里
2. 到场签到 → 调用**解冻**，钱原路全额退回用户
3. 爽约 → 调用**分账**，把钱划给实际到场的参与者
4. 活动取消 → 调用**解冻**，全额退回

**平台在这中间做的事情只有一件：判定"该不该解冻"。** 我们不收款、不付款、不做结算。

